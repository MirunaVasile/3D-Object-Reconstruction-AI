"""Algoritm PSGN"""

import torch
import torch.nn as nn
import torchvision.models as models
import torchvision.transforms as transforms
from torch.utils.data import Dataset, DataLoader, random_split
import cv2
import numpy as np
import os
import json

# --- 1. CONDUCTA DE DATE  ---
class Pix3D_PSGN_Dataset(Dataset):
    def __init__(self, raw_dir, pc_dir, ann_path, max_samples=200):
        with open(ann_path, 'r') as f:
            annotations = json.load(f)

        self.data = []
        for i, item in enumerate(annotations[:max_samples]):
            pc_fname = os.path.join(pc_dir, f'pc_{i:05d}.npy')
            img_path = os.path.join(raw_dir, item.get('img', ''))

            # Verificăm să existe și poza 2D și norul de puncte 3D
            if os.path.exists(pc_fname) and os.path.exists(img_path):
                self.data.append({'img_path': img_path, 'pc_path': pc_fname})

        self.transform = transforms.Compose([
            transforms.ToPILImage(),
            transforms.Resize((224, 224)),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ])

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        item = self.data[idx]

        # Citim Poza 2D
        img = cv2.imread(item['img_path'])
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        img_tensor = self.transform(img)

        # Citim Punctele 3D
        pc = np.load(item['pc_path']).astype(np.float32)
        # centrare
        pc = pc - np.mean(pc, axis=0)
        pc = pc / np.max(np.linalg.norm(pc, axis=1))
        pc_tensor = torch.from_numpy(pc)

        return {'imagine': img_tensor, 'puncte': pc_tensor}


# --- 2. PSGN ---
class PSGN(nn.Module):
    def __init__(self, num_points=2048):
        super(PSGN, self).__init__()
        self.num_points = num_points

        # Encoder (ResNet)
        resnet = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
        self.encoder = nn.Sequential(*list(resnet.children())[:-1])

        # Decoder (Multi Linear Perception)
        self.decoder = nn.Sequential(
            nn.Linear(512, 1024),
            nn.ReLU(),
            nn.Linear(1024, 2048),
            nn.ReLU(),
            nn.Linear(2048, num_points * 3),
            nn.Tanh()
        )

    def forward(self, x):
        x = self.encoder(x)
        x = x.view(x.size(0), -1)
        puncte = self.decoder(x)
        puncte = puncte.view(-1, self.num_points, 3)
        return puncte

# --- 3. FUNCȚIA DE EROARE  ---
def chamfer_distance(p1, p2):
    dist = torch.cdist(p1, p2)
    min_dist_p1 = torch.min(dist, dim=2)[0]
    min_dist_p2 = torch.min(dist, dim=1)[0]
    return torch.mean(min_dist_p1) + torch.mean(min_dist_p2)

# --- 4. PREGĂTIREA ȘI ÎMPĂRȚIREA DATELOR (TRAIN / TEST) ---
RAW_DIR = '/content/drive/MyDrive/3D_Reconstruction_Project/data/pix3d_raw'
PC_DIR = '/content/drive/MyDrive/3D_Reconstruction_Project/data/pix3d_preproc/pointclouds'
ANN_PATH = os.path.join(RAW_DIR, 'pix3d.json')

dataset_complet = Pix3D_PSGN_Dataset(RAW_DIR, PC_DIR, ANN_PATH)

total_imagini = len(dataset_complet)
train_size = int(0.8 * total_imagini)
test_size = total_imagini - train_size

print(f" Dataset total: {total_imagini} perechi valide.")
print(f" Împart datele: {train_size} pentru Antrenament, {test_size} pentru Testare.")

train_dataset, test_dataset = random_split(dataset_complet, [train_size, test_size])

dataloader_train = DataLoader(train_dataset, batch_size=8, shuffle=True, num_workers=2)
dataloader_test = DataLoader(test_dataset, batch_size=8, shuffle=False, num_workers=2)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = PSGN(num_points=2048).to(device)
optimizer = torch.optim.Adam(model.parameters(), lr=0.0001)

print(f"\n Încep antrenamentul pe {device}...\n")

# --- 5. START ANTRENAMENT ---
epoci = 50

for epoca in range(epoci):
    model.train()
    loss_total = 0.0

    for batch in dataloader_train:
        imagini = batch['imagine'].to(device)
        puncte_reale = batch['puncte'].to(device)

        optimizer.zero_grad()
        puncte_prezise = model(imagini)

        loss = chamfer_distance(puncte_prezise, puncte_reale)
        loss.backward()

        optimizer.step()

        loss_total += loss.item()

    loss_mediu = loss_total / len(dataloader_train)
    print(f" Epoca [{epoca+1:02d}/{epoci}] -> Eroare (Chamfer Loss): {loss_mediu:.4f}")

# --- 6. SALVAREA MODELULUI ---
torch.save(model.state_dict(), '/content/drive/MyDrive/3D_Reconstruction_Project/psgn_model.pth')
